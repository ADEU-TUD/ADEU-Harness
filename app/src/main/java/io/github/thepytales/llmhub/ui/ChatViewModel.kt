/** Creates a new, not yet saved conversation with the configured defaults. */
fun newConversation(c: AppContainer, model: String? = null): Conversation {
    val s = c.settings.current
    val wanted = model ?: s.defaultModel
    val available = c.models.state.value.liveIds
    val chosen = if (available == null || wanted in available) wanted
    else c.models.state.value.pickable.firstOrNull()?.id ?: wanted
    val env = s.defaultEnvId.takeIf { id -> id.isNotEmpty() && c.environments.get(id) != null }
    return Conversation(model = chosen, githubEnabled = s.hasGitHub && s.githubAutoTools, envId = env)
}

/**
 * State of one chat. A new chat ([initialId] null) only lives in memory until the first message is sent.
 * [initialModel] / [initialPersona] preset a new chat (from the model list or a template).
 * Answers are generated by [io.github.thepytales.llmhub.agent.ChatRuns], so they continue when the screen
 * or the app is closed; while one runs, this view model mirrors its state.
 */
@OptIn(ExperimentalCoroutinesApi::class)
class ChatViewModel(
    private val c: AppContainer,
    initialId: String?,
    initialModel: String? = null,
    initialPersona: String? = null,
) : ViewModel() {
    private val template = initialPersona?.let { TemplateLibrary.find(it, c.templates.current) }

    /** Prompt template a new chat was started with (from the template library); the screen fills it in. */
    val startTemplate: Template? = template?.takeIf { it.kind == TemplateKind.PROMPT }

    private val _conversation = MutableStateFlow(
        if (initialId == null) {
            newConversation(c, initialModel).copy(folderId = NewChatFolder.take()).let { it.copy(model = Privacy.suitableModel(c, it.folderId, it.model)) }.let { conv ->
                template?.takeIf { it.kind == TemplateKind.PERSONA }?.let { t -> conv.copy(systemPrompt = t.content, persona = t.name) } ?: conv
            }
        } else c.runs.get(initialId)?.conversation?.value ?: c.chats.get(initialId)
    )
    val state: StateFlow<Conversation?> = _conversation.asStateFlow()

    /** Id of this chat; a new chat already has its final id. */
    val chatId: String = initialId ?: _conversation.value!!.id

    private val isRunning get() = c.runs.get(chatId) != null

    val running: StateFlow<Boolean> = c.runs.runs.map { chatId in it }
        .stateIn(viewModelScope, SharingStarted.Eagerly, isRunning)

    /** Write action waiting for the user's permission. */
    val pending: StateFlow<PendingAction?> = c.runs.runs.flatMapLatest { it[chatId]?.pending ?: flowOf(null) }
        .stateIn(viewModelScope, SharingStarted.Eagerly, null)

    private val _transcribing = MutableStateFlow(false)
    val transcribing: StateFlow<Boolean> = _transcribing.asStateFlow()

    private val _toasts = MutableSharedFlow<String>(extraBufferCapacity = 8)
    val toasts: SharedFlow<String> = _toasts

    /** The chat was deleted elsewhere (drawer); nothing may be saved anymore. */
    private val _deleted = MutableStateFlow(false)
    val deleted: StateFlow<Boolean> = _deleted.asStateFlow()

    /** Whether this chat has been written to the repository at least once. */
    private var saved = initialId != null

    init {
        c.runs.get(chatId)?.let(::attach)
        viewModelScope.launch {
            if (_conversation.value == null && initialId != null) {
                // The repository loads asynchronously at app start.
                c.chats.awaitLoaded()
                _conversation.value = c.runs.get(chatId)?.conversation?.value ?: c.chats.get(initialId)
            }
        }
        viewModelScope.launch {
            c.runs.notices.collect { (id, message) -> if (id == chatId) _toasts.tryEmit(message) }
        }
        viewModelScope.launch {
            // Renaming, pinning or moving the chat in the drawer changes the stored copy.
            c.chats.conversations.collect { list ->
                val cur = _conversation.value ?: return@collect
                val stored = list.firstOrNull { it.id == cur.id }
                if (stored == null) {
                    if (c.chats.loaded.value && cur.messages.isNotEmpty() && saved) _deleted.value = true
                    return@collect
                }
                if (stored.title != cur.title || stored.pinned != cur.pinned || stored.folderId != cur.folderId || stored.unread != cur.unread) {
                    _conversation.value = cur.copy(title = stored.title, pinned = stored.pinned, folderId = stored.folderId, unread = stored.unread)
                }
            }
        }
    }

    /** Shows the state of [run] while it is in progress and keeps its final state. */
    private fun attach(run: ChatRun) {
        viewModelScope.launch {
            val mirror = launch { run.conversation.collect { _conversation.value = it } }
            run.join()
            mirror.cancel()
            _conversation.value = run.conversation.value
        }
    }

    private fun update(transform: (Conversation) -> Conversation) {
        val cur = _conversation.value ?: return
        _conversation.value = transform(cur)
    }

    private fun persist() {
        val conv = _conversation.value ?: return
        if (_deleted.value || conv.messages.isEmpty() || isRunning) return
        saved = true
        c.chats.save(conv.copy(updatedAt = System.currentTimeMillis()))
    }

    /** Saves settings changes without moving the chat to the top of the list. */
    private fun edit(transform: (Conversation) -> Conversation) {
        if (c.runs.edit(chatId, transform)) return
        update(transform)
        val conv = _conversation.value ?: return
        if (!_deleted.value && conv.messages.isNotEmpty()) {
            saved = true
            c.chats.save(conv)
        }
    }

    /** The user looks at the chat: results are no longer new. */
    fun markRead() {
        if (_conversation.value?.unread == true || c.chats.get(chatId)?.unread == true) {
            update { it.copy(unread = false) }
            c.chats.modify(chatId) { it.copy(unread = false) }
        }
        Notifier.cancel(c.appContext, chatId)
    }

    fun answerPending(allow: Boolean, always: Boolean = false) = c.runs.answer(chatId, allow, always)

    /** Write actions in this chat run without asking (or ask again). */
    fun setAutoApprove(on: Boolean) = edit { it.copy(autoApprove = on) }

    fun setModel(model: String) = edit { it.copy(model = model) }

    fun setSystemPrompt(prompt: String, persona: String? = null) =
        edit { it.copy(systemPrompt = prompt.ifBlank { null }, persona = if (prompt.isBlank()) null else persona) }

    fun setGitHub(enabled: Boolean, repos: List<LinkedRepo>) =
        edit { it.copy(githubEnabled = enabled).withRepos(if (enabled) repos else emptyList()) }

    fun setEnvironment(envId: String?) = edit { it.copy(envId = envId) }

    fun rename(title: String) = edit { it.copy(title = title.trim().ifBlank { it.title }) }

    fun setPinned(pinned: Boolean) = edit { it.copy(pinned = pinned) }

    fun moveToFolder(folderId: String?) = edit { it.copy(folderId = folderId, model = Privacy.suitableModel(c, folderId, it.model)) }

    fun deleteChat() {
        c.runs.stop(chatId)
        _deleted.value = true
        c.chats.delete(chatId)
    }

    /** Sends a message; with [template] its hidden instructions go along (see [ChatMessage.instructions]). */
    fun send(text: String, images: List<String>, files: List<FileAttachment>, template: Template? = null) {
        val conv = _conversation.value ?: return
        if (isRunning || (text.isBlank() && images.isEmpty() && files.isEmpty())) return
        val isFirst = conv.messages.none { it.role == "user" }
        val message = ChatMessage(
            role = "user", content = text.trim(), images = images, files = files,
            template = template?.name, instructions = template?.instructions?.ifBlank { null },
        )
        update {
            it.appendToThread(message).copy(
                title = if (isFirst) makeTitle(text, files) else it.title,
            )
        }
        persist()
        connectMentionedRepo(text)
        startAgent()
    }

    /**
     * A template the app fills in itself (the letter): the document is built from [values] right away, without the
     * model, and shown like a create_document call – so follow-up requests ("freundlicher formulieren") can change it.
     */
    fun sendDirect(text: String, values: Map<String, String>, template: Template) {
        val conv = _conversation.value ?: return
        val kind = template.direct ?: return
        if (isRunning) return
        val isFirst = conv.messages.none { it.role == "user" }
        val subject = values["Betreff"]?.trim().orEmpty()
        val message = ChatMessage(role = "user", content = text.trim(), template = template.name, instructions = template.instructions.ifBlank { null })
        update {
            it.appendToThread(message).copy(
                title = if (isFirst) (if (subject.isNotEmpty()) "${template.name}: $subject" else template.name).take(60) else it.title,
            )
        }
        persist()
        _building.value = true
        viewModelScope.launch {
            try {
                val (args, output) = c.documentTools.createDirect(kind, values)
                val call = ToolCall(id = "direct_" + java.util.UUID.randomUUID().toString().take(8), name = "create_document", arguments = args.toString())
                val gaps = output.file?.let { c.documentTools.openPlaceholders(File(it)) }.orEmpty()
                val note = buildString {
                    append("Ihr ${template.name} ist fertig – Ihr Text wurde so übernommen, wie Sie ihn eingegeben haben.")
                    if (gaps.isNotEmpty()) append(" Noch offen: ${gaps.joinToString(", ")} – tippen Sie am Dokument auf „Ausfüllen“.")
                    append("\n\nÄnderungen können Sie einfach hier schreiben, z.B. „Formuliere den zweiten Absatz freundlicher“ oder „Ergänze die Frist 30. November“.")
                }
                update {
                    it.appendToThread(ChatMessage(role = "assistant", toolCalls = listOf(call)))
                        .appendToThread(ChatMessage(role = "tool", content = output.text, toolCallId = call.id, toolName = call.name, file = output.file))
                        .appendToThread(ChatMessage(role = "assistant", content = note))
                }
            } catch (e: CancellationException) {
                throw e
            } catch (e: Exception) {
                update { it.appendToThread(ChatMessage(role = "assistant", error = true, content = "Der ${template.name} konnte nicht erstellt werden: ${e.message ?: e.javaClass.simpleName}")) }
            } finally {
                _building.value = false
                persist()
            }
        }
    }

    /** A document of a direct template is being built. */
    private val _building = MutableStateFlow(false)
    val building: StateFlow<Boolean> = _building.asStateFlow()

    /** Sends an edited version of a user message as new branch (the old version stays reachable). */
    fun editMessage(message: ChatMessage, newText: String) {
        if (isRunning || newText.isBlank()) return
        update { it.addVersion(message, message.copy(id = java.util.UUID.randomUUID().toString(), content = newText.trim(), createdAt = System.currentTimeMillis())) }
        persist()
        connectMentionedRepo(newText)
        startAgent()
    }

    /** Generates a new version of the answer to [userMessage], optionally with another model. */
    fun regenerate(userMessage: ChatMessage, model: String? = null) {
        if (isRunning) return
        update { conv -> conv.branchAfter(userMessage).let { if (model != null) it.copy(model = model) else it } }
        persist()
        startAgent()
    }

    /** Shows another version of a message. */
    fun showVersion(message: ChatMessage) {
        if (isRunning) return
        edit { it.select(message) }
    }

    /** A GitHub link in the message turns the GitHub tools on and links that repository to the chat. */
    private fun connectMentionedRepo(text: String) {
        val repo = GitHubTools.findRepoUrl(text) ?: return
        val conv = _conversation.value ?: return
        if (!c.settings.current.hasGitHub) {
            _toasts.tryEmit("Für den Zugriff auf GitHub-Repositories bitte ein gültiges GitHub-Token in den Einstellungen eintragen.")
            return
        }
        val linked = conv.linkedRepos
        if (conv.githubEnabled && linked.any { it.name.equals(repo, ignoreCase = true) }) return
        _toasts.tryEmit(if (conv.githubEnabled) "Repository verknüpft: $repo" else "GitHub-Werkzeuge aktiviert: $repo")
        edit { it.copy(githubEnabled = true).withRepos(it.linkedRepos + LinkedRepo(repo)) }
    }

    /** Re-runs the model after an error (drops the failed answer). */
    fun retry() {
        if (isRunning) return
        update { conv ->
            var cv = conv
            while (true) {
                val last = cv.thread().lastOrNull() ?: break
                if (last.role == "assistant" && (last.error || (last.content.isBlank() && last.toolCalls.isEmpty()))) {
                    cv = cv.removeSubtree(last.id)
                    last.parentId?.let { pid -> cv.messages.firstOrNull { it.id == pid } }?.let { cv = cv.branchAfter(it) }
                } else break
            }
            cv
        }
        _conversation.value?.thread()?.lastOrNull { it.role == "user" }?.let { connectMentionedRepo(it.content) }
        persist()
        startAgent()
    }

    fun stop() = c.runs.stop(chatId)

    private fun startAgent() {
        val conv = _conversation.value ?: return
        if (_deleted.value) return
        attach(c.runs.start(conv))
    }

    fun speak(id: String, text: String) = c.speaker.toggle(id, text)

    fun transcribe(file: File, onText: (String) -> Unit) {
        viewModelScope.launch {
            _transcribing.value = true
            try {
                val local = !Privacy.level(c, _conversation.value?.folderId).allowsUniServer
                val text = if (local) {
                    // Data protection level "Nur auf diesem Gerät": recognized on the device.
                    c.transcription.recognizeShort(file)
                        ?: throw IllegalStateException("In diesem Projekt bleibt Sprache auf dem Gerät – dafür unter Einstellungen › Transkription ein Erkennungsmodell laden.")
                } else c.llm.transcribe(c.settings.current.sttModel, file)
                if (text.isBlank()) _toasts.tryEmit("Keine Sprache erkannt.") else onText(text)
            } catch (e: CancellationException) {
                throw e
            } catch (e: Exception) {
                _toasts.tryEmit("Spracherkennung fehlgeschlagen: ${e.message}")
            } finally {
                _transcribing.value = false
            }
        }
    }

    override fun onCleared() {
        persist()
    }

    private fun makeTitle(text: String, files: List<FileAttachment>): String {
        val t = text.trim().lineSequence().firstOrNull().orEmpty()
            .ifBlank { files.firstOrNull()?.name ?: "Bild-Chat" }
        return if (t.length > 48) t.take(48).trimEnd() + "…" else t
    }
}

/** Splits `<think>…</think>` reasoning that some models put into the content. */
fun splitThinking(content: String): Pair<String?, String> {
    val t = content.trimStart()
    if (t.startsWith("<think>")) {
        val end = t.indexOf("</think>")
        return if (end < 0) t.removePrefix("<think>").trim() to ""
        else t.substring(7, end).trim() to t.substring(end + 8).trimStart()
    }
    val end = content.indexOf("</think>")
    if (end >= 0) return content.substring(0, end).trim() to content.substring(end + 8).trimStart()
    return null to content
}
