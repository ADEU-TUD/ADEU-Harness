package io.github.thepytales.llmhub.agent

import org.mozilla.javascript.BaseFunction
import org.mozilla.javascript.Context
import org.mozilla.javascript.ContextFactory
import org.mozilla.javascript.NativeArray
import org.mozilla.javascript.NativeObject
import org.mozilla.javascript.Scriptable
import org.mozilla.javascript.ScriptableObject
import org.mozilla.javascript.Undefined

/**
 * Runs JavaScript from the model in a sandbox (run_javascript): exact arithmetic, statistics and tables from
 * attached CSV/Excel text instead of guessed numbers. No access to Java classes, files or the network; a time
 * limit stops endless loops. Output is what the script prints plus the value of its last expression.
 */
object ScriptRunner {
    const val TIME_LIMIT_MS = 10_000L
    const val MAX_OUTPUT = 20_000

    data class Result(val output: String, val error: String?)

    /** Bound to our factory, so it asks the factory below about the time limit (Context() would use the global one). */
    private class Limited(factory: ContextFactory, val deadline: Long) : Context(factory)

    private val factory = object : ContextFactory() {
        override fun makeContext(): Context = Limited(this, System.currentTimeMillis() + TIME_LIMIT_MS).apply {
            // Interpreted: Android cannot load generated bytecode, and it allows counting instructions.
            optimizationLevel = -1
            instructionObserverThreshold = 10_000
            setClassShutter { false }
            languageVersion = Context.VERSION_ES6
        }

        override fun observeInstructionCount(cx: Context, instructionCount: Int) {
            if (System.currentTimeMillis() > (cx as Limited).deadline) {
                throw Error("Zeitlimit von ${TIME_LIMIT_MS / 1000} s überschritten (Endlosschleife?)")
            }
        }
    }

    /** Helpers available to every script: parseCSV, sum, mean, median, sd, round, table. */
    private const val PRELUDE = """
        var console = { log: function() { print(Array.prototype.slice.call(arguments).map(function(a) { return typeof a === 'object' ? JSON.stringify(a) : String(a); }).join(' ')); } };
        function parseCSV(text, sep) {
          text = String(text).replace(/\r/g, '');
          if (!sep) { var first = text.split('\n')[0]; sep = (first.split(';').length > first.split(',').length) ? ';' : (first.indexOf('\t') >= 0 ? '\t' : ','); }
          var rows = [], row = [], cell = '', q = false;
          for (var i = 0; i < text.length; i++) {
            var ch = text[i];
            if (q) { if (ch === '"') { if (text[i + 1] === '"') { cell += '"'; i++; } else q = false; } else cell += ch; }
            else if (ch === '"') q = true;
            else if (ch === sep) { row.push(cell); cell = ''; }
            else if (ch === '\n') { row.push(cell); rows.push(row); row = []; cell = ''; }
            else cell += ch;
          }
          if (cell !== '' || row.length) { row.push(cell); rows.push(row); }
          rows = rows.filter(function(r) { return r.some(function(c) { return c.trim() !== ''; }); });
          var head = rows.shift() || [];
          return rows.map(function(r) { var o = {}; head.forEach(function(h, j) { var v = (r[j] || '').trim(); var n = Number(v.replace(',', '.')); o[h.trim()] = (v !== '' && !isNaN(n) && /^-?[0-9.,]+$/.test(v)) ? n : v; }); return o; });
        }
        function sum(a) { return a.reduce(function(s, x) { return s + Number(x); }, 0); }
        function mean(a) { return a.length ? sum(a) / a.length : NaN; }
        function median(a) { var s = a.map(Number).sort(function(x, y) { return x - y; }); var m = Math.floor(s.length / 2); return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2; }
        function sd(a) { var m = mean(a); return Math.sqrt(sum(a.map(function(x) { return (x - m) * (x - m); })) / (a.length - 1)); }
        function round(x, n) { var f = Math.pow(10, n || 0); return Math.round(x * f) / f; }
        function numbers(a) { return a.filter(function(x) { return x !== null && x !== undefined && String(x).trim() !== ''; }).map(function(x) { return typeof x === 'number' ? x : Number(String(x).replace(',', '.')); }).filter(function(x) { return x === x; }); }
        function freq(a) { var f = {}; a.forEach(function(x) { var k = (x === undefined || x === null || String(x).trim() === '') ? '(leer)' : String(x).trim(); f[k] = (f[k] || 0) + 1; }); return f; }
        function percent(part, total, n) { return total ? round(100 * part / total, n === undefined ? 1 : n) : 0; }
        function column(rows, name) { return rows.map(function(r) { return r[name]; }); }
        function describe(a) { var v = numbers(a); return { n: v.length, M: round(mean(v), 2), SD: round(sd(v), 2), Md: median(v), Min: Math.min.apply(null, v), Max: Math.max.apply(null, v) }; }
        function table(rows) { if (!rows.length) return ''; var h = Object.keys(rows[0]); return '| ' + h.join(' | ') + ' |\n|' + h.map(function() { return ' --- '; }).join('|') + '|\n' + rows.map(function(r) { return '| ' + h.map(function(k) { return String(r[k]); }).join(' | ') + ' |'; }).join('\n'); }
    """

    /** Runs [code]; [files] (name to text) are available as `files["name"]` and `fileList`. */
    fun run(code: String, files: Map<String, String> = emptyMap()): Result {
        val out = StringBuilder()
        return try {
            factory.call { cx ->
                val scope: ScriptableObject = cx.initSafeStandardObjects()
                ScriptableObject.putProperty(scope, "print", object : BaseFunction() {
                    override fun call(cx: Context, scope: Scriptable, thisObj: Scriptable?, args: Array<out Any?>): Any {
                        if (out.length < MAX_OUTPUT) out.append(args.joinToString(" ") { Context.toString(it) }).append('\n')
                        return Undefined.instance
                    }
                })
                val fileObj = cx.newObject(scope)
                files.forEach { (name, text) -> ScriptableObject.putProperty(fileObj, name, text) }
                ScriptableObject.putProperty(scope, "files", fileObj)
                ScriptableObject.putProperty(scope, "fileList", cx.newArray(scope, files.keys.toTypedArray<Any>()))
                cx.evaluateString(scope, PRELUDE, "prelude", 1, null)
                val value = cx.evaluateString(scope, code, "script", 1, null)
                if (value != null && value !is Undefined) {
                    val shown = if (value is NativeObject || value is NativeArray) stringify(cx, scope, value) else Context.toString(value)
                    out.append("→ ").append(shown).append('\n')
                }
                null
            }
            Result(out.toString().take(MAX_OUTPUT).ifBlank { "(keine Ausgabe – nutze print(...) oder gib am Ende einen Wert zurück)" }, null)
        } catch (e: Throwable) {
            val message = when (e) {
                is org.mozilla.javascript.RhinoException -> e.details() + (e.lineNumber().takeIf { it > 0 }?.let { " (Zeile $it)" } ?: "")
                else -> e.message ?: e.javaClass.simpleName
            }
            Result(out.toString().take(MAX_OUTPUT), message)
        }
    }

    private fun stringify(cx: Context, scope: Scriptable, value: Any): String {
        ScriptableObject.putProperty(scope, "__v", value)
        return Context.toString(cx.evaluateString(scope, "JSON.stringify(__v, null, 1)", "json", 1, null))
    }
}
